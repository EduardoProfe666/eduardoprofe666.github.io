/**
 * Writes `src/data/skill-icons.generated.ts` from the slugs in
 * `src/data/skills.ts`.
 *
 *   node scripts/generate-skill-icons.mjs
 *
 * The page used to mount `react-icon-cloud`, which pulled thirty-odd brand
 * marks from cdn.simpleicons.org at runtime — the only thing this site fetched
 * from anywhere, on a page whose whole premise is that it does not. Each mark
 * is a few hundred bytes of path data, so fetching them once at build time and
 * shipping them costs less than the DNS lookup did.
 *
 * Needs the network, and only when the skill list changes. If a slug has been
 * withdrawn from Simple Icons it fails loudly rather than shipping a hole:
 * give that skill a `mono` in `skills.ts` instead.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const source = new URL("../src/data/skills.ts", import.meta.url);
const target = new URL("../src/data/skill-icons.generated.ts", import.meta.url);

/**
 * Brand colours are published for one background — usually a white page — and
 * several of them are flatly unusable on the other. GitHub Copilot ships as
 * #000000, which on a #08090a page is not a dark logo, it is an absent one;
 * JavaScript's #F7DF1E is 1.4:1 against white and barely more visible there.
 *
 * So each mark is stored twice, blended toward black or white only as far as it
 * takes to clear 3:1 against the background it will sit on. A mark
 * that is already legible is left exactly as its owner specified it.
 */
const LIGHT_BG = [255, 255, 255];
const DARK_BG = [8, 9, 10];
const BLACK = [0, 0, 0];
const WHITE = [255, 255, 255];
/** WCAG's bar for graphical objects. A brand mark is one. */
const FLOOR = 3;

const toRgb = (hex) => [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16));
const toHex = (rgb) =>
  "#" + rgb.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");

function luminance([r, g, b]) {
  const f = (v) => {
    v /= 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}

function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

function adapt(rgb, background, toward) {
  if (contrast(rgb, background) >= FLOOR) return rgb;
  for (let t = 0.05; t < 1; t += 0.05) {
    const blended = rgb.map((v, i) => v + (toward[i] - v) * t);
    if (contrast(blended, background) >= FLOOR) return blended;
  }
  return toward;
}

const text = await readFile(source, "utf8");
// Anything with a `mono` draws itself, so it needs no icon.
const entries = [...text.matchAll(/\{\s*slug:\s*"([^"]+)"([^}]*)\}/g)]
  .filter(([, , rest]) => !rest.includes("mono:"))
  .map(([, slug]) => slug);

const unique = [...new Set(entries)];
console.log(`Fetching ${unique.length} marks…`);

const icons = {};
for (const slug of unique) {
  const res = await fetch(`https://cdn.simpleicons.org/${slug}`);
  if (!res.ok) {
    throw new Error(
      `Simple Icons has no "${slug}" (HTTP ${res.status}). Give it a \`mono\` in skills.ts.`
    );
  }
  const svg = await res.text();
  const hex = svg.match(/fill="#([0-9a-fA-F]{3,8})"/)?.[1];
  const title = svg.match(/<title>([^<]*)<\/title>/)?.[1];
  const path = svg.match(/ d="([^"]+)"/)?.[1];
  if (!hex || !title || !path) throw new Error(`Could not parse ${slug}`);
  const rgb = toRgb(hex);
  icons[slug] = {
    title,
    path,
    light: toHex(adapt(rgb, LIGHT_BG, BLACK)),
    dark: toHex(adapt(rgb, DARK_BG, WHITE)),
  };
  process.stdout.write(".");
}
console.log();

const body = Object.entries(icons)
  .map(
    ([slug, i]) =>
      `  ${JSON.stringify(slug)}: {\n    title: ${JSON.stringify(i.title)},\n    light: ${JSON.stringify(i.light)},\n    dark: ${JSON.stringify(i.dark)},\n    path: ${JSON.stringify(i.path)},\n  },`
  )
  .join("\n");

await writeFile(
  fileURLToPath(target),
  `// Generated by scripts/generate-skill-icons.mjs — do not edit.\n` +
    `// Brand marks from Simple Icons (CC0), inlined so the page ships them.\n\n` +
    `export interface SkillIcon {\n  title: string;\n  /** Brand colour, nudged only if it would be illegible on that background. */\n  light: string;\n  dark: string;\n  path: string;\n}\n\n` +
    `export const SKILL_ICONS: Record<string, SkillIcon> = {\n${body}\n};\n`,
  "utf8"
);
console.log(`Wrote src/data/skill-icons.generated.ts (${unique.length} marks).`);
